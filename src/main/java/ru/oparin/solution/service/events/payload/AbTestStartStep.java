package ru.oparin.solution.service.events.payload;

/**
 * Шаг асинхронного старта А/Б-теста (каждый шаг — отдельное событие очереди).
 */
public enum AbTestStartStep {
    /** Получить галерею карточки и сохранить control локально. */
    RESOLVE_CARD,
    /**
     * Устаревший шаг: раньше варианты писались в слоты 2+ и затирали галерею.
     * События из очереди пропускаются без вызова WB.
     */
    UPLOAD_VARIANT,
    /** Устаревший шаг, пропускается. */
    REFRESH_URLS,
    /** Вернуть исходный набор медиа, если старт успел затереть слоты 2+. */
    RESTORE_GALLERY,
    /** Выставить control в слот 1 и перевести тест в ENABLED. */
    APPLY_CONTROL
}
